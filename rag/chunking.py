"""
SMART PADDY PROJECT
RAG Text Chunking

Purpose:
    Split RAG documents into smaller overlapping text chunks.

Input:
    Documents loaded by document_loader.py

Metadata:
    Metadata generated by metadata.py

Output:
    Chunk records containing:
        - chunk_id
        - text
        - source
        - variety
        - category
        - document_type
"""

from typing import Dict, List

from rag.config import CHUNK_SIZE, CHUNK_OVERLAP
from rag.document_loader import load_all_documents
from rag.metadata import build_document_metadata


# ============================================================
# BASIC TEXT CLEANING
# ============================================================

def clean_chunk_text(text: str) -> str:
    """
    Clean unnecessary whitespace inside a chunk.
    """

    if not text:
        return ""

    # Replace repeated spaces
    text = " ".join(text.split())

    return text.strip()


# ============================================================
# SPLIT TEXT INTO CHUNKS
# ============================================================

def split_text(
    text: str,
    chunk_size: int = CHUNK_SIZE,
    chunk_overlap: int = CHUNK_OVERLAP,
) -> List[str]:
    """
    Split a large document into overlapping chunks.

    Example:

        chunk 1
        -------------------------
        text text text text text

                  overlap
                     ↓
        chunk 2
        -------------------------
              text text text text

    Character-based chunking is used here because the source
    documents are already structured knowledge documents.
    """

    if not text:
        return []

    if chunk_size <= 0:
        raise ValueError(
            "chunk_size must be greater than 0."
        )

    if chunk_overlap < 0:
        raise ValueError(
            "chunk_overlap cannot be negative."
        )

    if chunk_overlap >= chunk_size:
        raise ValueError(
            "chunk_overlap must be smaller than chunk_size."
        )

    cleaned_text = clean_chunk_text(text)

    if not cleaned_text:
        return []

    # If the complete text is smaller than the chunk size,
    # return it as one chunk.
    if len(cleaned_text) <= chunk_size:
        return [cleaned_text]

    chunks = []

    start = 0
    text_length = len(cleaned_text)

    while start < text_length:

        end = min(
            start + chunk_size,
            text_length
        )

        chunk = cleaned_text[start:end]

        # ----------------------------------------------------
        # Try to avoid cutting a sentence/word in the middle.
        # ----------------------------------------------------

        if end < text_length:

            # Prefer sentence boundary
            last_period = chunk.rfind(". ")

            # Otherwise prefer newline-like boundary
            last_semicolon = chunk.rfind("; ")

            # Otherwise prefer comma boundary
            last_comma = chunk.rfind(", ")

            best_boundary = max(
                last_period,
                last_semicolon,
                last_comma,
            )

            # Only move boundary if it is reasonably far
            # inside the chunk.
            minimum_boundary = int(
                chunk_size * 0.60
            )

            if best_boundary >= minimum_boundary:

                end = start + best_boundary + 1

                chunk = cleaned_text[start:end]

        chunk = clean_chunk_text(chunk)

        if chunk:
            chunks.append(chunk)

        # ----------------------------------------------------
        # Move forward while keeping overlap.
        # ----------------------------------------------------

        next_start = end - chunk_overlap

        if next_start <= start:
            next_start = end

        start = next_start

    return chunks


# ============================================================
# CREATE CHUNKS FOR ONE DOCUMENT
# ============================================================

def chunk_document(
    document: Dict,
    chunk_size: int = CHUNK_SIZE,
    chunk_overlap: int = CHUNK_OVERLAP,
) -> List[Dict]:
    """
    Convert one document into chunk records.
    """

    metadata = build_document_metadata(document)

    text = document.get("raw_text", "")

    text_chunks = split_text(
        text=text,
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
    )

    chunk_records = []

    for index, chunk_text in enumerate(
        text_chunks,
        start=1,
    ):

        chunk_id = (
            f"{metadata['file_name']}"
            f"__chunk_{index:04d}"
        )

        chunk_record = {
            "chunk_id": chunk_id,
            "text": chunk_text,
            "chunk_index": index,
            "file_name": metadata["file_name"],
            "file_path": metadata["file_path"],
            "source": metadata["source"],
            "variety": metadata["variety"],
            "category": metadata["category"],
            "document_type": metadata["document_type"],
        }

        chunk_records.append(chunk_record)

    return chunk_records


# ============================================================
# CREATE CHUNKS FOR ALL DOCUMENTS
# ============================================================

def chunk_all_documents(
    chunk_size: int = CHUNK_SIZE,
    chunk_overlap: int = CHUNK_OVERLAP,
) -> List[Dict]:
    """
    Load all RAG documents and create chunks.
    """

    documents = load_all_documents()

    all_chunks = []

    for document in documents:

        document_chunks = chunk_document(
            document=document,
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
        )

        all_chunks.extend(document_chunks)

    return all_chunks


# ============================================================
# GROUP CHUNKS BY VARIETY
# ============================================================

def count_chunks_by_variety(
    chunks: List[Dict],
) -> Dict[str, int]:
    """
    Count how many chunks belong to each variety/category.
    """

    counts = {}

    for chunk in chunks:

        variety = chunk["variety"]

        if variety not in counts:
            counts[variety] = 0

        counts[variety] += 1

    return counts


# ============================================================
# GROUP CHUNKS BY DOCUMENT
# ============================================================

def count_chunks_by_document(
    chunks: List[Dict],
) -> Dict[str, int]:
    """
    Count chunks generated from each source document.
    """

    counts = {}

    for chunk in chunks:

        file_name = chunk["file_name"]

        if file_name not in counts:
            counts[file_name] = 0

        counts[file_name] += 1

    return counts


# ============================================================
# PRINT CHUNK SUMMARY
# ============================================================

def print_chunk_summary(
    chunks: List[Dict],
) -> None:
    """
    Print a readable chunking summary.
    """

    print()
    print("=" * 70)
    print("SMART PADDY - RAG CHUNKING TEST")
    print("=" * 70)

    print()
    print(f"Total chunks created: {len(chunks)}")

    # --------------------------------------------------------
    # Variety counts
    # --------------------------------------------------------

    print()
    print("CHUNKS BY VARIETY / CATEGORY")
    print("-" * 70)

    variety_counts = count_chunks_by_variety(chunks)

    for variety in sorted(variety_counts):

        print(
            f"{variety:<20} : "
            f"{variety_counts[variety]}"
        )

    # --------------------------------------------------------
    # Document counts
    # --------------------------------------------------------

    print()
    print("CHUNKS BY DOCUMENT")
    print("-" * 70)

    document_counts = count_chunks_by_document(chunks)

    for file_name in sorted(document_counts):

        print(
            f"{file_name:<40} : "
            f"{document_counts[file_name]}"
        )

    # --------------------------------------------------------
    # First few chunks preview
    # --------------------------------------------------------

    print()
    print("FIRST 5 CHUNKS PREVIEW")
    print("-" * 70)

    for chunk in chunks[:5]:

        print()
        print(f"Chunk ID : {chunk['chunk_id']}")
        print(f"Variety  : {chunk['variety']}")
        print(f"Category : {chunk['category']}")
        print(
            f"Type     : {chunk['document_type']}"
        )

        preview = chunk["text"][:300]

        if len(chunk["text"]) > 300:
            preview += "..."

        print(f"Text     : {preview}")


# ============================================================
# VALIDATE CHUNKS
# ============================================================

def validate_chunks(
    chunks: List[Dict],
) -> bool:
    """
    Validate the generated chunk records.
    """

    if not chunks:

        print("ERROR: No chunks were created.")

        return False

    required_fields = {
        "chunk_id",
        "text",
        "chunk_index",
        "file_name",
        "file_path",
        "source",
        "variety",
        "category",
        "document_type",
    }

    valid_varieties = {
        "Sannalu",
        "Bondalu",
        "RNR 15048",
        "Swarna",
        "common",
    }

    for index, chunk in enumerate(chunks):

        # ----------------------------------------------------
        # Required field check
        # ----------------------------------------------------

        missing_fields = (
            required_fields - set(chunk.keys())
        )

        if missing_fields:

            print(
                f"ERROR: Chunk {index + 1} "
                f"is missing fields:"
            )

            for field in sorted(missing_fields):
                print(f"  - {field}")

            return False

        # ----------------------------------------------------
        # Empty text check
        # ----------------------------------------------------

        if not chunk["text"].strip():

            print(
                f"ERROR: Empty text in "
                f"{chunk['chunk_id']}"
            )

            return False

        # ----------------------------------------------------
        # Variety check
        # ----------------------------------------------------

        if chunk["variety"] not in valid_varieties:

            print(
                f"ERROR: Invalid variety "
                f"'{chunk['variety']}' in "
                f"{chunk['chunk_id']}"
            )

            return False

    return True


